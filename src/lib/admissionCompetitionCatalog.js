function numberedEntries(tier, names) {
  return names.map((name, index) => ({
    code: `${tier}-${String(index + 1).padStart(2, '0')}`,
    tier,
    name,
    comparisonEvent: '',
    detailNote: '',
    sortOrder: index + 1,
  }))
}

export const ADMISSION_COMPETITION_CATALOG = Object.freeze([
  ...numberedEntries('international', internationalNames),
  ...numberedEntries('national', nationalNames),
  ...countyEntries.map(([name, comparisonEvent, detailNote], index) => ({
    code: `county-${String(index + 1).padStart(2, '0')}`,
    tier: 'county',
    name,
    comparisonEvent,
    detailNote,
    sortOrder: index + 1,
  })),
])

export const COMPETITION_TIER_LABELS = Object.freeze({
  international: '國際性',
  national: '全國性',
  county: '縣市級（雲林縣）',
})

export function competitionsForTier(tier) {
  return ADMISSION_COMPETITION_CATALOG.filter((item) => item.tier === tier)
}

export function competitionByCode(code) {
  return ADMISSION_COMPETITION_CATALOG.find((item) => item.code === code) || null
}
