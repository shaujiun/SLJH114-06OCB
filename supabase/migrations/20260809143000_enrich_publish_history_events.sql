update public.history_questions
set
  status = 'published',
  published_at = coalesce(published_at, now()),
  updated_at = now()
where question_code like 'ka-%';

do $$
declare
  target_count integer;
  incomplete_count integer;
  published_question_count integer;
begin
  select count(*) into target_count
  from public.history_events
  where event_code ~ '^h[34]c[1-6]-[0-9]{2}$';

  select count(*) into incomplete_count
  from public.history_events
  where event_code ~ '^h[34]c[1-6]-[0-9]{2}$'
    and (
      status <> 'published'
      or length(btrim(cause_text)) = 0
      or length(btrim(process_text)) = 0
      or length(btrim(impact_text)) = 0
    );

  if target_count <> 104 then
    raise exception '八年級歷史事件應有 104 筆，實際為 % 筆。', target_count;
  end if;

  if incomplete_count <> 0 then
    raise exception '仍有 % 筆事件未發布或缺少原因、經過、影響。', incomplete_count;
  end if;

  select count(*) into published_question_count
  from public.history_questions
  where question_code like 'ka-%'
    and status = 'published';

  if published_question_count <> 149 then
    raise exception '已發布的八年級正式試題應有 149 題，實際為 % 題。', published_question_count;
  end if;
end
$$;
